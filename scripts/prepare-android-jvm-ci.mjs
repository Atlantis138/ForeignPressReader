import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tauriRoot = join(repoRoot, "src-tauri");
const androidRoot = join(tauriRoot, "gen", "android");
const cargoMetadata = spawnSync(
  "cargo",
  [
    "metadata",
    "--format-version",
    "1",
    "--locked",
    "--manifest-path",
    join(tauriRoot, "Cargo.toml"),
  ],
  {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  },
);

if (cargoMetadata.status !== 0) {
  process.stderr.write(cargoMetadata.stderr);
  throw new Error("cargo metadata failed while locating tauri-android");
}

const metadata = JSON.parse(cargoMetadata.stdout);
const tauriAndroidRoots = [
  ...new Set(
    metadata.packages
      .filter((item) => item.name === "tauri")
      .map((item) => join(dirname(item.manifest_path), "mobile", "android")),
  ),
];

if (tauriAndroidRoots.length !== 1) {
  throw new Error(
    `Expected one locked tauri-android project, found ${tauriAndroidRoots.length}`,
  );
}

const [tauriAndroidRoot] = tauriAndroidRoots;
if (!existsSync(join(tauriAndroidRoot, "build.gradle.kts"))) {
  throw new Error("The locked tauri crate does not contain its Android project");
}

const escapeGradleString = (value) =>
  value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
const platformPluginRoot = join(tauriRoot, "plugins", "fpr-platform", "android");

writeFileSync(
  join(androidRoot, "tauri.settings.gradle"),
  `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
include ':fpr-platform-plugin'
project(':fpr-platform-plugin').projectDir = new File("${escapeGradleString(platformPluginRoot)}")
include ':tauri-android'
project(':tauri-android').projectDir = new File("${escapeGradleString(tauriAndroidRoot)}")
`,
  "utf8",
);

writeFileSync(
  join(androidRoot, "app", "tauri.build.gradle.kts"),
  `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
val implementation by configurations
dependencies {
  implementation("androidx.lifecycle:lifecycle-process:2.10.0")
  implementation(project(":fpr-platform-plugin"))
  implementation(project(":tauri-android"))
}
`,
  "utf8",
);

console.log("Prepared ignored Tauri Android Gradle support files for JVM checks.");
